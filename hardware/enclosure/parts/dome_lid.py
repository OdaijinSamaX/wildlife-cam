"""カメラ窓に使う既製品 — ドリンク用の透明ドーム蓋.

DIM_SOURCE = "measured:2026-08-25"（ノギス実測）。試作機で実用的な映像が
撮れている実績のある部品で、これを前提に設計する。

| 項目 | 実測 | 備考 |
|---|---|---|
| 口径（縁の径） | 76.0 mm | カップの縁に嵌まる側 |
| 深さ | 32.2 mm | 縁の平面から頂点まで |
| **頂点の平らな窓の直径** | **25.0 mm** | **穴ではなく塞がった平面**。像が歪まない |
| 肉厚 | 0.4 mm | **変更できない**。消耗品として扱う |

## 頂点は「平らな窓」であって穴ではない

光は平面を通るので像が歪まない。**曲面越しに撮るのではない。**
試作機ではドームが外に出る向きで取り付け、カメラはドームの中に入っていた。

## 設計を支配する条件: レンズは頂点の窓から 16.0 mm 以内

対角半角 37.98 度（`parts/cam_module3.half_angle_deg()`）を φ25 の平窓で
確保できる距離は

```
L_max = (25.0 / 2) / tan(37.98 度) = 12.5 / 0.7806 = 16.01 mm
```

**フランジ位置（32.2 mm 奥）ではまったく足りない。** そこでの半角は

```
atan(12.5 / 32.2) = 21.2 度   ->  対角 42.4 度。四隅が大きく欠ける
```

したがって **筐体の前壁から支持構造を前方に伸ばし、カメラを 16 mm 圏内まで
送り出して、その上からドームを被せる**構成になる。防犯カメラと同じ作り。

## 嵌合部（2026-08-25 に断面を実測。**ただし 2 件が既存記録と両立しない**）

このドーム蓋にはカップの縁に嵌まる溝が元から成形されている。筐体側に
カップの縁と同形状の突起を印刷すれば、ドームが設計どおり嵌合する。
工具なしで着脱でき、傷んだら買って交換できる。

### ★ 保持はボルトが担う（**2026-08-25 に方針を訂正した**）

実測で **抜け止めビードが無い**ことが分かった（⑤）。ひっかかりが無いので、
**既製品の嵌合だけでは保持力が当てにできない。**
このため「保持は既製品の嵌合に任せる」という**旧記述は誤り**で、
**保持はドームを留める取付ボルト 3 本（非等分角のポカヨケ）が担う。**
嵌合が受け持つのは**位置決めだけ**である。防水は下に敷く O リングが受け持つ。

**この役割分担が締め代の決め方を変える。** 保持を嵌合に頼らないので、
締め代は「抜けない強さ」ではなく「割れない範囲で位置が出る」だけあればよい（D-025）。

### 実測（2026-08-25・1 枚を放射方向に切断して断面をノギス測定）

| # | 項目 | 実測 | 扱い |
|---|---|---|---|
| ① | 溝の内径（内壁どうし） | 76.9 | **要再測定**（下記） |
| ② | 溝の深さ（半径方向） | 7.1 | **採用しない。幾何が成立しない**（下記） |
| ③ | 溝の高さ（軸方向） | 7.3 | 採用（`GROOVE_H`） |
| ④ | 縁の肉厚（溝の外側の壁） | 0.9 | 採用（`RIM_WALL_T`） |
| ⑤ | 抜け止めビード | **無し** | 採用。上記の方針訂正の根拠 |
| ⑥ | 溝の入口から蓋の縁まで | 未測定 | `UNMEASURED` に残す |
| ⑦ | 嵌合の締め代 | 対のカップが無く測れない | **設計側で決めた**（D-025） |

測定条件はひだの無い平らな箇所。0.4 mm の PET に軽く当てているので **±0.1〜0.2**。

### 食い違い (1): `RIM_DIA` 76.0 と ① 76.9 は同じ形状では両立しない

**① は「内壁どうし」= 内側の寸法、`RIM_DIA` は「口径（縁の径）」= 外側の寸法。**
**内側 76.9 > 外側 76.0 は成り立たない。**

人間が立てた「差 0.9 が ④ の肉厚と一致するので内壁/外壁の取り違えでは」という
仮説は**検算で否定された**。内径と外径の差は **2 x 肉厚 = 1.8** であって 0.9 ではない。
0.9 の一致は数値の偶然である。

**したがって両方を残し、どちらも印刷リブの径には使わない。** ①② が揃うまで
`window_snoot.py` のリブは引き直せない（`GROOVE_ID` は推定のまま据え置き）。

### 食い違い (2): ② 7.1 は「半径方向の食い込み」ではありえない

② が本当に半径方向なら、スカートの外径は

    ① + 2 x ② + 2 x ④ = 76.9 + 14.2 + 1.8 = 92.9

となり、ドーム本体の外径 76.0 より**片側 8.5 mm 外へ張り出す。**
ドリンク蓋の形として成立しない。

一方 ② 7.1 と ③ 7.3 はほぼ同値で、推定 `LIP_H = 6.0`（縁の立ち上がり）に近い。
**②③ は同じ「スカートの高さ」を 2 通りに測ったものと見るのが自然**で、
**半径方向の食い込みはまだ測れていない。** よって `GROOVE_DEPTH` は推定のまま残す。

### ④ 0.9 が素材厚 0.4 の倍なのは、縁が折り返されているため

`WALL_T` 0.4 の 2 枚ぶん 0.8 ≒ 0.9。成形品の縁がカールして二重になっていれば
自然に説明がつく（断面写真で確認できるはず）。

## 材料と交換周期

肉厚 0.4 mm の PET（と思われる）。**850 nm の近赤外は問題なく透過する**が、
紫外線で白濁して脆化する。交換周期の目安は `docs/window-options.md`。
"""

import math

import cadquery as cq

from harness.component import make_component

#: 2026-08-25 に嵌合部の断面を追加実測（外形 4 項目は 2026-08-22 のまま）。
DIM_SOURCE = "measured:2026-08-25"

RIM_DIA = 76.0        # 実測（口径）
DEPTH = 32.2          # 実測（縁の平面から頂点まで）
WINDOW_DIA = 25.0     # 実測（頂点の平らな窓）
WALL_T = 0.4          # 実測。変更できない

#: 嵌合部で**まだ決まっていないもの**。2026-08-25 の実測で 7 -> 4 に減った。
#: **①② は「測ったが採用できない」ので、埋まったのではなく差し戻し**である。
UNMEASURED = (
    "嵌合溝の内径（**要再測定**。既存 RIM_DIA 76.0 と実測 76.9 が両立しない）",
    "嵌合溝の深さ（半径方向の食い込み量。**要再測定**。実測 7.1 は幾何が成立しない）",
    "溝の入口から蓋の縁までの距離",
    "嵌合の締め代（対になるカップが無く測れない。**設計側で決めた** -> D-025）",
)

#: **再測定のときに人間へ渡す指示。** 切った断面が手元にある間にやること。
REMEASURE_NOTES = (
    "① 溝の内径: **内壁どうし**か**外壁どうし**かを明記して測り直す。"
    "あわせて 2026-08-22 の RIM_DIA 76.0 が蓋のどこを測ったものかを特定する"
    "（スカート外径 / 溝の内壁 / ドーム最大径のどれか）",
    "② 溝の深さ: **半径方向**（蓋の中心軸に垂直）に、溝の底から開口までの"
    "食い込み量を測る。7 mm 級なら形が成立しないので、1〜3 mm を想定して読む",
    "⑥ 溝の入口から蓋の縁まで: 軸方向の距離",
)

# --- 嵌合部 --------------------------------------------------------------
GROOVE_ID = 75.4      # **推定のまま**（① が確定しないと置き換えられない）
GROOVE_DEPTH = 1.2    # **推定のまま**（② は採用できない。上の docstring 参照）
GROOVE_H = 7.3        # 実測 2026-08-25（③ 軸方向の幅。旧 3.0 は推定だった）
RIM_WALL_T = 0.9      # 実測 2026-08-25（④ 溝の外側の壁。素材 0.4 の折り返しと見られる）
HAS_BEAD = False      # 実測 2026-08-25（⑤ 抜け止めビードは無い）
LIP_H = 6.0           # 推定: 縁の立ち上がり高さ（③ 7.3 と近く、要再確認）

#: **嵌合の締め代（直径差）。設計側で決めた値。** 根拠は D-025。
#: 保持は取付ボルト 3 本が担うので、嵌合は**位置決めだけ**でよい。
#: PET 0.4 mm のフープひずみを 0.3% 以下に抑える = 直径で 0.23 mm 以下。
INTERFERENCE = 0.2    # 設計値 2026-08-25（D-025）


def max_lens_distance(window_dia: float | None = None,
                      half_angle_deg: float | None = None) -> float:
    """平窓 φd で半角 θ を確保できる、レンズから窓までの最大距離."""
    from parts import cam_module3

    d = WINDOW_DIA if window_dia is None else window_dia
    a = cam_module3.half_angle_deg() if half_angle_deg is None else half_angle_deg
    return (d / 2) / math.tan(math.radians(a))


def half_angle_at(distance: float) -> float:
    """レンズが窓から distance のときに得られる対角半角（度）."""
    return math.degrees(math.atan((WINDOW_DIA / 2) / distance))


def model() -> cq.Workplane:
    """縁の平面を z=0、ドームは +z に張り出す（肉厚 0.4 の殻）.

    形は「縁から頂点へ向かう回転体」で近似している。実物の断面は測っていない。
    """
    r_rim = RIM_DIA / 2
    r_win = WINDOW_DIA / 2
    # 縁 -> 頂点を 2 本の直線で近似（下部は立ち上がり、上部は絞り込み）
    pts = [
        (r_rim, 0.0),
        (r_rim, LIP_H),
        (r_win, DEPTH),
        (0.0, DEPTH),
        (0.0, DEPTH - WALL_T),
        (r_win - WALL_T, DEPTH - WALL_T),
        (r_rim - WALL_T, LIP_H),
        (r_rim - WALL_T, 0.0),
    ]
    return (
        cq.Workplane("XZ")
        .polyline(pts)
        .close()
        .revolve(360, (0, 0, 0), (0, 1, 0))
    )


def apex_ring(clearance: float = 0.0) -> cq.Workplane:
    """**頂点の平窓の外側**（= 像として使えない曲面部）を表す円環.

    視野円錐がこの環に当たったら、四隅が曲面越しになる。`fov` チェックに
    COMPONENTS として渡すことで、16 mm 条件を機械が検証できる。
    ドーム本体は透明なので COMPONENTS に入れない（透過は判定できないため）。
    """
    c = clearance
    return (
        cq.Workplane("XY")
        .circle(RIM_DIA / 2)
        .circle(max(WINDOW_DIA / 2 - c, 0.1))
        .extrude(WALL_T + 2 * c)
        .translate((0, 0, DEPTH - WALL_T - c))
    )


def envelope(clearance: float = 0.0) -> cq.Workplane:
    c = clearance
    return (
        cq.Workplane("XY")
        .circle(RIM_DIA / 2 + c)
        .extrude(DEPTH + c)
    )


ENVELOPE = envelope(0.5)


def place(at=(0, 0, 0), rotate=(0, 0, 0)):
    return make_component(
        "Dome lid (drink lid)", model, envelope, at=at, rotate=rotate,
        dimension_source=DIM_SOURCE,
        notes=(
            "口径 76.0 / 深さ 32.2 / 頂点の平窓 φ25.0 / 肉厚 0.4（実測）。"
            "レンズは平窓から 16.0 mm 以内。嵌合溝は 2026-08-25 に断面実測（①② は要再測定）。"
            "PET は紫外線で白濁するので消耗品として扱う。"
        ),
    )


def place_apex_ring(at=(0, 0, 0), rotate=(0, 0, 0)):
    """視野判定用。平窓の外側だけを部品として置く."""
    return make_component(
        "dome apex ring (non-imaging)", apex_ring, apex_ring, at=at, rotate=rotate,
        dimension_source=DIM_SOURCE,
        notes="頂点の平窓 φ25.0 の外側。ここに視野が掛かると四隅が曲面越しになる",
    )
